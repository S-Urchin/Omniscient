const { app, BrowserWindow, ipcMain, dialog, protocol, net, shell, Menu } = require('electron');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { pathToFileURL } = require('url');
const { Store } = require('./db');
const { Worlds } = require('./worlds');

const IMAGE_EXTS = ['png', 'jpg', 'jpeg', 'gif', 'webp', 'bmp', 'avif'];
const MIME = { jpg: 'jpeg', svg: 'svg+xml' };

// Images are served to the UI through custom schemes instead of raw file paths:
//   omni-img://<file>             an image in the open world's library
//   omni-world://<worldId>/<file> a world's profile picture
protocol.registerSchemesAsPrivileged([
  { scheme: 'omni-img', privileges: { standard: true, secure: true, supportFetchAPI: true } },
  { scheme: 'omni-world', privileges: { standard: true, secure: true, supportFetchAPI: true } },
]);

const rootDir = process.env.OMNISCIENT_DATA_DIR || app.getPath('userData');
let worlds;
let current = null; // { id, dir, imageDir }
let store = null;
let win;

function imagePath(file) {
  // Only bare file names generated by us are valid; anything else could escape the folder.
  if (!current) throw new Error('No world is open');
  if (!/^[a-f0-9-]+\.[a-z0-9]+$/i.test(file)) throw new Error('Invalid image name');
  return path.join(current.imageDir, file);
}

function copyIntoLibrary(src) {
  const ext = path.extname(src).slice(1).toLowerCase();
  if (!IMAGE_EXTS.includes(ext)) return null;
  const file = `${crypto.randomUUID()}.${ext}`;
  fs.copyFileSync(src, imagePath(file));
  return file;
}

function removeImageFile(file) {
  try { fs.unlinkSync(imagePath(file)); } catch {}
}

// ---- worlds ----

async function openWorld(id) {
  closeWorld();
  const dir = worlds.dir(id);
  const imageDir = path.join(dir, 'images');
  fs.mkdirSync(imageDir, { recursive: true });
  store = await Store.open(path.join(dir, 'omniscient.sqlite'));
  current = { id, dir, imageDir };
  const series = worlds.seriesOf(id);
  if (series.length === 1) store.assignOrphanEvents(id);
  const w = worlds.update(id, { lastOpenedAt: new Date().toISOString() });
  win.setTitle(`${w.name} — Omniscient`);
  return { ...w, series };
}

// Runs fn against a story's library whether or not it is the one currently open.
async function withLibrary(id, fn) {
  if (current && worlds.get(current.id).folder === worlds.get(id).folder) return fn(store, current.imageDir);
  const dir = worlds.dir(id);
  const s = await Store.open(path.join(dir, 'omniscient.sqlite'));
  try {
    return fn(s, path.join(dir, 'images'));
  } finally {
    s.close();
  }
}

function closeWorld() {
  if (store) store.close();
  store = null;
  current = null;
  if (win) win.setTitle('Omniscient');
}

function requireWorld() {
  if (!store) throw new Error('No world is open');
  return store;
}

function setAvatar(id, src) {
  const w = worlds.get(id);
  const dir = worlds.dir(id);
  if (w.avatar) { try { fs.unlinkSync(path.join(dir, w.avatar)); } catch {} }
  let avatar = null;
  if (src) {
    const ext = path.extname(src).slice(1).toLowerCase();
    if (!IMAGE_EXTS.includes(ext)) throw new Error('Unsupported image type');
    avatar = `avatar-${crypto.randomUUID()}.${ext}`;
    fs.mkdirSync(dir, { recursive: true });
    fs.copyFileSync(src, path.join(dir, avatar));
  }
  worlds.update(id, { avatar });
}

function registerIpc() {
  const handle = (channel, fn) => ipcMain.handle(channel, (_e, ...args) => fn(...args));

  handle('worlds:list', () => worlds.list());
  handle('worlds:current', () => (current ? worlds.get(current.id) : null));
  handle('worlds:open', id => openWorld(id));
  handle('worlds:close', () => closeWorld());
  handle('worlds:create', async ({ name, color, avatarPath, kind, relatedTo }) => {
    // Claim the original story's untagged events before a second story joins its library.
    if (kind !== 'standalone' && relatedTo && worlds.seriesOf(relatedTo).length === 1) {
      await withLibrary(relatedTo, s => s.assignOrphanEvents(relatedTo));
    }
    const w = worlds.create({ name, color, kind, relatedTo });
    if (avatarPath) setAvatar(w.id, avatarPath);
    return w.id;
  });
  handle('worlds:update', (id, { name, color, avatarPath, removeAvatar }) => {
    worlds.update(id, { name, color });
    if (avatarPath) setAvatar(id, avatarPath);
    else if (removeAvatar) setAvatar(id, null);
    if (current && current.id === id) win.setTitle(`${name} — Omniscient`);
  });
  handle('worlds:delete', async id => {
    const dir = worlds.dir(id);
    const shared = worlds.seriesOf(id).length > 1;
    if (current && current.id === id) closeWorld();
    if (shared) {
      // Other stories still use this library: remove only this story's own events.
      const files = await withLibrary(id, s => s.deleteStoryEvents(id));
      for (const f of files) { try { fs.unlinkSync(path.join(dir, 'images', f)); } catch {} }
    } else if (fs.existsSync(dir)) {
      // Recycle Bin rather than a permanent delete, so a mistaken click is recoverable.
      await shell.trashItem(dir);
    }
    if (shared) {
      const w = worlds.get(id);
      if (w.avatar) { try { fs.unlinkSync(path.join(dir, w.avatar)); } catch {} }
    }
    worlds.remove(id);
  });
  handle('worlds:pickImage', async () => {
    const res = await dialog.showOpenDialog(win, {
      title: 'Choose a picture for this world',
      properties: ['openFile'],
      filters: [{ name: 'Images', extensions: IMAGE_EXTS }],
    });
    if (res.canceled) return null;
    const file = res.filePaths[0];
    const ext = path.extname(file).slice(1).toLowerCase();
    const dataUrl = `data:image/${MIME[ext] || ext};base64,${fs.readFileSync(file).toString('base64')}`;
    return { path: file, dataUrl };
  });

  handle('entries:list', filter => requireWorld().listEntries(filter));
  handle('entries:get', id => requireWorld().getEntry(id));
  // New events belong to the open story; characters, places etc. are shared by the series.
  handle('entries:create', data => requireWorld().createEntry({ ...data, story_id: data.type === 'Event' ? current.id : null }));
  handle('entries:update', (id, patch) => {
    const s = requireWorld();
    if (patch.type === 'Event' && !s.getEntry(id).story_id) patch.story_id = current.id;
    s.updateEntry(id, patch);
  });
  handle('entries:backlinks', id => requireWorld().backlinks(id));
  handle('entries:delete', id => requireWorld().deleteEntry(id).forEach(removeImageFile));
  handle('meta:get', () => {
    const s = requireWorld();
    const types = s.typeCounts();
    // Keep the count shown on the world's profile tile current.
    worlds.setEntryCount(current.id, types.reduce((n, t) => n + t.count, 0));
    return { tags: s.listTags(), types, labels: s.relationLabels() };
  });

  handle('images:importPaths', (entryId, paths) => {
    const files = paths.map(copyIntoLibrary).filter(Boolean);
    requireWorld().addImages(entryId, files);
    return files.length;
  });
  handle('images:importBuffer', (entryId, ext, buffer) => {
    ext = String(ext).toLowerCase();
    if (!IMAGE_EXTS.includes(ext)) return 0;
    const file = `${crypto.randomUUID()}.${ext}`;
    fs.writeFileSync(imagePath(file), Buffer.from(buffer));
    requireWorld().addImages(entryId, [file]);
    return 1;
  });
  handle('images:pick', async entryId => {
    const res = await dialog.showOpenDialog(win, {
      title: 'Add images',
      properties: ['openFile', 'multiSelections'],
      filters: [{ name: 'Images', extensions: IMAGE_EXTS }],
    });
    if (res.canceled) return 0;
    const files = res.filePaths.map(copyIntoLibrary).filter(Boolean);
    requireWorld().addImages(entryId, files);
    return files.length;
  });
  handle('images:update', (id, patch) => requireWorld().updateImage(id, patch));
  handle('images:delete', id => {
    const file = requireWorld().deleteImage(id);
    if (file) removeImageFile(file);
  });

  handle('relations:add', rel => requireWorld().addRelation(rel));
  handle('relations:update', (id, patch) => requireWorld().updateRelation(id, patch));
  handle('relations:delete', id => requireWorld().deleteRelation(id));

  handle('graph:get', () => requireWorld().graph());
  handle('graph:savePositions', positions => requireWorld().saveGraphPositions(positions));
  handle('timeline:reorder', ids => requireWorld().reorderEvents(ids));

  handle('board:savePositions', positions => requireWorld().saveBoardPositions(positions));
  handle('board:notes', () => requireWorld().listBoardNotes(current.id));
  handle('board:createNote', note => requireWorld().createBoardNote(current.id, note));
  handle('board:updateNote', (id, patch) => requireWorld().updateBoardNote(id, patch));
  handle('board:deleteNote', id => requireWorld().deleteBoardNote(id));

  handle('app:openDataFolder', () => shell.openPath(current ? current.dir : rootDir));
  handle('app:backup', async () => {
    requireWorld();
    const res = await dialog.showOpenDialog(win, {
      title: 'Choose a folder for the backup',
      properties: ['openDirectory', 'createDirectory'],
    });
    if (res.canceled) return null;
    const name = worlds.get(current.id).name.replace(/[<>:"/\\|?*]+/g, '').trim() || 'World';
    const dest = path.join(res.filePaths[0], `${name} backup ${new Date().toISOString().slice(0, 10)}`);
    fs.cpSync(current.dir, dest, { recursive: true });
    return dest;
  });
}

function createWindow() {
  win = new BrowserWindow({
    width: 1400,
    height: 900,
    minWidth: 900,
    minHeight: 600,
    backgroundColor: '#15161a',
    title: 'Omniscient',
    webPreferences: {
      preload: path.join(__dirname, 'preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
    },
  });
  // The window title shows the open world; don't let the page's <title> overwrite it.
  win.on('page-title-updated', e => e.preventDefault());
  win.loadFile(path.join(__dirname, 'renderer', 'index.html'));
  // Links in notes open in the system browser, never inside the app.
  // Reloading the app page itself (used when switching worlds) is allowed.
  win.webContents.on('will-navigate', (e, url) => { if (url !== win.webContents.getURL()) e.preventDefault(); });
  win.webContents.setWindowOpenHandler(({ url }) => {
    if (/^https?:/.test(url)) shell.openExternal(url);
    return { action: 'deny' };
  });
}

function serveFile(file) {
  return net.fetch(pathToFileURL(file).toString());
}

// Worlds that have never been opened in this version (e.g. the adopted pre-profiles library)
// get their entry count read once so their tile isn't wrong.
async function countUnopenedWorlds() {
  for (const w of worlds.list()) {
    const file = path.join(worlds.dir(w.id), 'omniscient.sqlite');
    if (w.lastOpenedAt || !fs.existsSync(file)) continue;
    const s = await Store.open(file);
    worlds.update(w.id, { entryCount: s.typeCounts().reduce((n, t) => n + t.count, 0) });
    s.close();
  }
}

app.whenReady().then(async () => {
  worlds = new Worlds(rootDir);
  await countUnopenedWorlds();

  protocol.handle('omni-img', req => {
    try {
      return serveFile(imagePath(decodeURIComponent(new URL(req.url).hostname)));
    } catch {
      return new Response('Not found', { status: 404 });
    }
  });
  protocol.handle('omni-world', req => {
    try {
      const url = new URL(req.url);
      const file = decodeURIComponent(url.pathname.slice(1));
      if (!/^avatar-[a-f0-9-]+\.[a-z0-9]+$/i.test(file)) throw new Error('Invalid avatar name');
      return serveFile(path.join(worlds.dir(url.hostname), file));
    } catch {
      return new Response('Not found', { status: 404 });
    }
  });

  if (app.isPackaged) Menu.setApplicationMenu(null);
  registerIpc();
  createWindow();
});

app.on('window-all-closed', () => {
  closeWorld();
  app.quit();
});
